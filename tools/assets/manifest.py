#!/usr/bin/env python3
"""The shipped-asset manifest (assets/manifest.toml): check it, and write ATTRIBUTION.md.

  python3 -I tools/assets/manifest.py check         # fails if anything under assets/ is unlisted,
                                                     # a source key is unknown, or a field is missing
  python3 -I tools/assets/manifest.py attribution   # writes ATTRIBUTION.md (repo root)

Sources are the "### Title (`key`)" entries of assets_src/SOURCES.md (title, source page,
author, licence); entries can also carry their own `credits` (the sounds). Standard library only
(tomllib, Python 3.11+). See docs/ASSETS_BRIEF.md §2.
"""
import fnmatch, os, re, subprocess, sys, tomllib

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ASSETS = os.path.join(ROOT, "assets")
FIELDS = ["name", "paths", "kind", "sources", "collision", "lod", "built_by"]
KINDS = {"texture_set", "mesh", "model", "sound", "text"}
COLLISION = {"none", "solid_cylinder", "breakable", "brush"}
# Shipped by the engine with every game (fonts); listed so the attribution is complete.
ENGINE = [
    ("Barlow, Barlow Condensed (fonts)", "The Barlow Project Authors (Jeremy Tribby)", "https://github.com/jpt/barlow", "SIL Open Font License 1.1", "UI text (engine/assets/fonts)"),
]


def load_manifest():
    with open(os.path.join(ASSETS, "manifest.toml"), "rb") as f:
        return tomllib.load(f)["asset"]


def load_sources():
    """{key: {title, url, author, licence}} from assets_src/SOURCES.md."""
    path = os.path.join(ROOT, "assets_src", "SOURCES.md")
    out, cur = {}, None
    for line in open(path, encoding="utf-8"):
        m = re.match(r"^### (.+?) \(`([^`]+)`\)", line)
        if m:
            cur = out.setdefault(m.group(2), {"title": m.group(1).strip()})
            continue
        if line.startswith("## "):
            cur = None
        if cur is None:
            continue
        for field, key in (("Source page", "url"), ("Author", "author"), ("Licence", "licence")):
            m = re.match(rf"^- \*\*{field}:\*\* (.+)", line.strip())
            if m:
                cur[key] = m.group(1).strip()
    return out


def shipped_files():
    """Tracked files under assets/ (what packaging copies), relative to assets/."""
    out = subprocess.run(["git", "ls-files", "assets"], cwd=ROOT, capture_output=True, text=True, check=True).stdout
    return sorted(p[len("assets/"):] for p in out.splitlines() if p)


def check():
    errors = []
    man, src = load_manifest(), load_sources()
    for a in man:
        for f in FIELDS:
            if f not in a:
                errors.append(f"{a.get('name', '?')}: missing field {f}")
        if a.get("kind") not in KINDS:
            errors.append(f"{a.get('name')}: kind {a.get('kind')!r} not one of {sorted(KINDS)}")
        if a.get("collision") not in COLLISION:
            errors.append(f"{a.get('name')}: collision {a.get('collision')!r} not one of {sorted(COLLISION)}")
        for k in a.get("sources", []):
            if k != "original" and k not in src:
                errors.append(f"{a['name']}: source {k!r} isn't in assets_src/SOURCES.md")
            elif k != "original" and not all(src[k].get(x) for x in ("url", "author", "licence")):
                errors.append(f"{a['name']}: SOURCES.md entry {k!r} lacks a source page, author or licence")
        if not a.get("sources") and not a.get("credits"):
            errors.append(f"{a['name']}: no sources and no credits")
    files = shipped_files()
    covered = set()
    for a in man:
        hits = [f for f in files if any(fnmatch.fnmatch(f, g) for g in a.get("paths", []))]
        if not hits:
            errors.append(f"{a['name']}: its paths match no shipped file")
        covered.update(hits)
    for f in files:
        if f not in covered:
            errors.append(f"assets/{f}: not in assets/manifest.toml")
    for e in errors:
        print("error:", e)
    print(f"{len(man)} entries, {len(files)} shipped files, {len(errors)} errors")
    return 1 if errors else 0


def attribution():
    man, src = load_manifest(), load_sources()
    rows = []  # (title, author, url, licence, used for)
    for a in man:
        used = f"{a['name']} ({', '.join(a['paths'])})"
        for k in a.get("sources", []):
            if k == "original":
                continue
            s = src[k]
            rows.append((s["title"], s.get("author", "?"), s.get("url", "?"), s.get("licence", "?"), used))
        for c in a.get("credits", []):
            rows.append((c["title"], c["author"], c["url"], c["licence"], used))
    rows += [(t, au, u, l, use) for (t, au, u, l, use) in ENGINE]
    lines = [
        "# Attribution",
        "",
        "Every outside asset Pacenote ships, generated by `python3 -I tools/assets/manifest.py attribution`",
        "from `assets/manifest.toml` and `assets_src/SOURCES.md` (don't edit by hand). The in-game credits",
        "are `assets/credits.txt`; CC BY entries must appear there. Everything not listed is original,",
        "made for Pacenote. Licences allowed: CC0, CC BY (credited), SIL OFL for fonts, Fab Standard (cooked files only) (docs/ASSETS_BRIEF.md §0).",
        "",
        "| Asset | Author | Source | Licence | Used for |",
        "|---|---|---|---|---|",
    ]
    seen = set()
    for r in rows:
        if r[:3] in seen:
            continue
        seen.add(r[:3])
        lines.append("| " + " | ".join(x.replace("|", "/") for x in r) + " |")
    needs_credit = [r for r in rows if "BY" in r[3].upper().replace("CC0", "")]
    lines += ["", "## Must be credited in game (CC BY)", ""]
    lines += [f"- {r[0]} by {r[1]} ({r[3]})" for r in needs_credit] or ["- none"]
    flagged = [a for a in man if a.get("note")]
    if flagged:
        lines += ["", "## Flags", ""] + [f"- **{a['name']}**: {a['note']}" for a in flagged]
    out = os.path.join(ROOT, "ATTRIBUTION.md")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{len(seen)} credits -> {out}")
    return 0


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    sys.exit({"check": check, "attribution": attribution}.get(cmd, lambda: sys.exit(__doc__))())
